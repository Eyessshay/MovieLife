-- Deletes only the Stage 16.4 reserved range and the transactional rows owned
-- by its reserved venue/showtimes. It never drops a schema or truncates a table.
USE movielife;
SET NAMES utf8mb4;

START TRANSACTION;

CREATE TEMPORARY TABLE demo_showtime_ids (id BIGINT PRIMARY KEY);
INSERT INTO demo_showtime_ids (id)
SELECT id FROM tb_showtime
WHERE venue_id BETWEEN 1604000000 AND 1604999999;

CREATE TEMPORARY TABLE demo_order_ids (id BIGINT PRIMARY KEY);
INSERT INTO demo_order_ids (id)
SELECT id FROM tb_ticket_order
WHERE showtime_id IN (SELECT id FROM demo_showtime_ids);

DELETE FROM tb_ticket_order_item
WHERE order_id IN (SELECT id FROM demo_order_ids);

DELETE FROM tb_showtime_seat
WHERE showtime_id IN (SELECT id FROM demo_showtime_ids);

DELETE FROM tb_ticket_order
WHERE id IN (SELECT id FROM demo_order_ids);

DELETE FROM tb_showtime
WHERE id IN (SELECT id FROM demo_showtime_ids);

DELETE FROM tb_ai_summary_task
WHERE target_type IN ('MOVIE', 'ACTIVITY')
  AND target_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_ai_review_summary
WHERE target_type IN ('MOVIE', 'ACTIVITY')
  AND target_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_collection
WHERE user_id BETWEEN 1604000000 AND 1604999999
   OR (target_type IN ('MOVIE', 'ACTIVITY', 'REVIEW')
       AND target_id BETWEEN 1604000000 AND 1604999999);

DELETE FROM tb_recommendation
WHERE user_id BETWEEN 1604000000 AND 1604999999
   OR target_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_user_behavior
WHERE user_id BETWEEN 1604000000 AND 1604999999
   OR target_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_review
WHERE id BETWEEN 1604000000 AND 1604999999
   OR user_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_follow
WHERE user_id BETWEEN 1604000000 AND 1604999999
   OR follow_user_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_venue_staff
WHERE id BETWEEN 1604000000 AND 1604999999
   OR user_id BETWEEN 1604000000 AND 1604999999
   OR venue_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_seat
WHERE hall_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_hall
WHERE venue_id BETWEEN 1604000000 AND 1604999999;

DELETE FROM tb_activity WHERE id BETWEEN 1604000000 AND 1604999999;
DELETE FROM tb_movie WHERE id BETWEEN 1604000000 AND 1604999999;
DELETE FROM tb_venue WHERE id BETWEEN 1604000000 AND 1604999999;
DELETE FROM tb_user WHERE id BETWEEN 1604000000 AND 1604999999;

DROP TEMPORARY TABLE demo_order_ids;
DROP TEMPORARY TABLE demo_showtime_ids;

COMMIT;

SELECT
  (SELECT COUNT(*) FROM tb_user WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_venue WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_hall WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_seat WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_activity WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_movie WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_review WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_ai_review_summary WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_ai_summary_task WHERE id BETWEEN 1604000000 AND 1604999999) +
  (SELECT COUNT(*) FROM tb_showtime WHERE venue_id BETWEEN 1604000000 AND 1604999999) AS remaining_demo_rows;
